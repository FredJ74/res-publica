function text(key,vars={}){
  const original=texts.fr[key];
  if(typeof original!=='string')return '';
  const locale=global.RP_I18N_GAME_ENABLED===true ? global.RPPlateauI18n?.language?.()||'fr' : 'fr';
  const template=texts[locale]?.[key]||original;
  return template.replace(/\{(\w+)\}/g,(full,key)=>Object.hasOwn(vars,key)?String(vars[key]):full);
}
function productLabel(id,original){
  const p=products[id];
  if(!p||original!==p[1])return original;
  return text(p[0]);
}
